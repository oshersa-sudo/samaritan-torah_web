def main():
    os.makedirs(DATA, exist_ok=True)

    periods = [{"name": n, "from": a, "to": b, "color": c} for n, a, b, c in PERIODS]
    emit.js(os.path.join(DATA, "periods.js"), "PERIODS", periods,
            "תקופות רקע — נבנה ע\"י scripts/build_data.py")

    priests = emit.build_priests(BLOCK1, BLOCK2, BLOCK3, MODERN, SRC_BOOK, SRC_WEB)
    rosters = [
        {"id": "priests", "name": "כהנים גדולים", "title": "הכהן הגדול",
         "color": "priest", "items": priests},
        {"id": "pm", "name": "ראשי ממשלת ישראל", "title": "ראש הממשלה",
         "color": "pm", "items": emit.build_roster(rulers_data.PMS, rulers_data.SRC_STATE)},
        {"id": "pres", "name": "נשיאי ישראל", "title": "נשיא המדינה",
         "color": "pres", "items": emit.build_roster(rulers_data.PRESIDENTS, rulers_data.SRC_STATE)},
    ]
    emit.js(os.path.join(DATA, "rosters.js"), "ROSTERS", rosters,
            "רצועות נושאי משרה — נבנה ע\"י scripts/build_data.py")

    evs = []
    for i, e in enumerate(events_data.EVENTS):
        d = dict(e)
        d["id"] = "e%03d" % i
        evs.append(d)
    evs.sort(key=lambda e: e["year"])

    people = emit.load_people()
    for p in people:
        evs.append({"id": p["id"], "year": p["year"], "to": None, "approx": True,
                    "track": "people", "title": p["name"],
                    "body": (p["period"] + "\n\n" + p["desc"]).strip(),
                    "src": "טבלת האישים של פרויקט אבני שהם (torah.db)"})

    emit.js(os.path.join(DATA, "events.js"), "TIMELINE_EVENTS", evs,
            "אירועי ציר הזמן — נבנה ע\"י scripts/build_data.py")

    pop = [{"year": y, "n": n, "kind": k, "note": note,
            "src": population_data.SRC.get(y, "")}
           for y, n, k, note in population_data.POPULATION]
    emit.js(os.path.join(DATA, "population.js"), "POPULATION", pop,
            "עקומת האוכלוסייה השומרונית — נבנה ע\"י scripts/build_data.py")

