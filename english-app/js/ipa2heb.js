/*
 * ipa2heb – ממיר תעתיק IPA (כפי שמופיע ב-Wiktionary/kaikki) לתעתיק הגייה בעברית.
 * התוצאה מקורבת (הגייה אנגלית אינה ממופה 1:1 לעברית), ומיועדת כעזר חזותי לצד
 * כפתור ההגייה הקולית שנותן את ההגייה האמיתית.
 * עובד גם בדפדפן (window.ipaToHebrew) וגם ב-Node (module.exports).
 */
(function (root) {
  // רצפים דו-תוויים קודם (דיפתונגים / תנועות ארוכות / עיצורים מורכבים)
  var MULTI = {
    "tʃ": "צ'",       // tʃ → צ'
    "dʒ": "ג'",       // dʒ → ג'
    "aɪ": "אַיי", // aɪ → אַיי
    "aʊ": "אַו",       // aʊ → אַו
    "ɔɪ": "וֹי",  // ɔɪ → וֹי
    "eɪ": "ֵיי",       // eɪ → ֵיי
    "oʊ": "וֹ",             // oʊ → וֹ
    "əʊ": "וֹ",        // əʊ → וֹ
    "ɪə": "ִיר",  // ɪə → ִיר
    "eə": "אֶר",       // eə → אֶר
    "ʊə": "וּר",  // ʊə → וּר
    "iː": "ִי",             // iː → ִי
    "uː": "וּ",             // uː → וּ
    "ɑː": "אָ",        // ɑː → אָ
    "ɔː": "וֹ",        // ɔː → וֹ
    "ɜː": "ֶר",        // ɜː → ֶר
    "ɚ": "ֶר",              // ɚ → ֶר
    "ɝ": "ֶר"               // ɝ → ֶר
  };
  var SINGLE = {
    "p": "פּ", "b": "בּ", "t": "ט", "d": "ד",
    "k": "ק", "g": "ג", "ɡ": "ג", "m": "מ", "n": "נ",
    "x": "כ", "ɫ": "ל", "ʔ": "",
    "ŋ": "נג",  // ŋ
    "f": "פ", "v": "ב",
    "θ": "ת'", "ð": "ד'", // θ ð
    "s": "ס", "z": "ז",
    "ʃ": "שׁ", "ʒ": "ז'", // ʃ ʒ
    "h": "ה", "l": "ל",
    "r": "ר", "ɹ": "ר", // ɹ
    "j": "י", "w": "ו",
    // תנועות בודדות
    "ɪ": "ִ",        // ɪ
    "i": "ִי",       // i
    "e": "ֶ", "ɛ": "ֶ", // e ɛ
    "æ": "אַ",  // æ
    "ə": "ֶ",        // ə (schwa)
    "ʌ": "ַא",  // ʌ
    "ɑ": "אָ",  // ɑ
    "ɒ": "וֹ",  // ɒ
    "ɔ": "וֹ",  // ɔ
    "ʊ": "וּ",  // ʊ
    "u": "וּ",       // u
    "ɜ": "ֶר"   // ɜ
  };
  // סופיות – החלפת אות אחרונה לצורת סופית
  var FINAL = { "מ": "ם", "נ": "ן", "פ": "ף", "צ": "ץ", "כ": "ך" };

  function clean(ipa) {
    if (!ipa) return "";
    // הסרת סוגריים, מפרידי הברות, סימני הטעמה ואורך
    return ipa.replace(/^[\/\[]|[\/\]]$/g, "")
              .replace(/[ˈˌ\.ː‿\s]/g, "");
  }

  function ipaToHebrew(ipa) {
    var s = clean(ipa);
    if (!s) return "";
    var out = "";
    for (var i = 0; i < s.length;) {
      var two = s.substr(i, 2);
      if (MULTI[two] != null) { out += MULTI[two]; i += 2; continue; }
      var one = s[i];
      if (SINGLE[one] != null) { out += SINGLE[one]; }
      // תו לא מוכר – מדלגים בשקט
      i += 1;
    }
    // צורה סופית לאות העיצור האחרונה (אם אין אחריה ניקוד)
    var m = out.match(/([א-ת])([^א-ת]*)$/);
    if (m && FINAL[m[1]] && !/[ְ-ּׁ]/.test(m[2])) {
      out = out.slice(0, m.index) + FINAL[m[1]] + m[2];
    }
    return out;
  }

  root.ipaToHebrew = ipaToHebrew;
  if (typeof module !== "undefined" && module.exports) module.exports = ipaToHebrew;
})(typeof window !== "undefined" ? window : globalThis);
